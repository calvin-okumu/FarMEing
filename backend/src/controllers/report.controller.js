const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');
const prisma = require('../lib/prisma');
const { checkProjectAccess } = require('../lib/project-access');

const getProjectData = async (id, userId) => {
  const { hasAccess, project } = await checkProjectAccess(id, userId);
  
  if (!hasAccess) return null;

  return await prisma.farmProject.findUnique({
    where: { id },
    include: {
      budgetItems: { where: { isDeleted: false } },
      expenses: { where: { isDeleted: false }, include: { payeeRecord: true } },
      workEntries: { where: { isDeleted: false }, include: { employee: true } },
      harvests: { where: { isDeleted: false } },
      sales: { where: { isDeleted: false } },
      inventoryItems: { where: { isDeleted: false } },
    },
  });
};

const generateProjectReport = async (req, res) => {
  const { id } = req.params;

  try {
    const project = await getProjectData(id, req.user.id);

    if (!project) {
      return res.status(404).json({ error: 'Project not found' });
    }

    const doc = new PDFDocument({ margin: 50 });

    // Set filename
    const filename = `Report_${project.name.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
    res.setHeader('Content-disposition', `attachment; filename="${filename}"`);
    res.setHeader('Content-type', 'application/pdf');

    doc.pipe(res);

    // ── Header ───────────────────────────────────────────────────────────────
    doc.fontSize(24).text('Farm Project Report', { align: 'center' });
    doc.fontSize(10).text('Generated by Shamba Mkononi', { align: 'center' });
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    doc.moveDown();

    // ── Project Info ─────────────────────────────────────────────────────────
    doc.fontSize(16).text(project.name, { underline: true });
    doc.fontSize(12).text(`Crop: ${project.crop || 'N/A'}`);
    doc.text(`Land Size: ${project.landSize} ${project.landUnit}`);
    doc.text(`Status: ${project.status || 'Active'}`);
    doc.text(`Date: ${project.startDate.toLocaleDateString()} - ${project.endDate ? project.endDate.toLocaleDateString() : 'Present'}`);
    doc.moveDown();

    // ── Financial Summary ────────────────────────────────────────────────────
    const totalBudget = project.budgetItems.reduce((sum, item) => sum + (item.total || 0), 0);
    const totalExpenses = project.expenses.reduce((sum, item) => sum + (item.amount || 0), 0);
    const totalLabor = project.workEntries.reduce((sum, item) => sum + (item.totalCost || 0), 0);
    const totalInventory = project.inventoryItems.reduce((sum, item) => sum + (item.totalCost || 0), 0);
    const totalRevenue = project.sales.reduce((sum, item) => sum + (item.totalAmount || 0), 0);
    const totalCost = totalExpenses + totalLabor + totalInventory;
    const netProfit = totalRevenue - totalCost;

    doc.fontSize(16).text('Financial Summary', { underline: true });
    doc.fontSize(12);
    doc.text(`Total Revenue: ${totalRevenue.toLocaleString()}`);
    doc.text(`Total Spending: ${totalCost.toLocaleString()}`);
    doc.text(`Net Profit/Loss: ${netProfit.toLocaleString()}`, { 
      color: netProfit >= 0 ? 'green' : 'red' 
    });
    doc.moveDown();

    // ── Breakdown ────────────────────────────────────────────────────────────
    doc.text(`- Operational Expenses: ${totalExpenses.toLocaleString()}`);
    doc.text(`- Labor Costs: ${totalLabor.toLocaleString()}`);
    doc.text(`- Inventory Purchases: ${totalInventory.toLocaleString()}`);
    doc.moveDown();

    // ── Production ───────────────────────────────────────────────────────────
    const totalHarvest = project.harvests.reduce((sum, item) => sum + (item.weight || 0), 0);
    doc.fontSize(16).text('Production', { underline: true });
    doc.fontSize(12).text(`Total Harvest: ${totalHarvest.toLocaleString()} kg`);
    doc.moveDown();

    // ── Footer ───────────────────────────────────────────────────────────────
    doc.fontSize(10).text('End of Report', doc.page.width - 100, doc.page.height - 50, { align: 'right' });

    doc.end();

  } catch (error) {
    console.error('PDF Export Error:', error);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate PDF report' });
    }
  }
};

const generateProjectExcelReport = async (req, res) => {
  const { id } = req.params;

  try {
    const project = await getProjectData(id, req.user.id);

    if (!project) {
      return res.status(404).json({ error: 'Project not found' });
    }

    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Shamba Mkononi';
    workbook.created = new Date();

    const summarySheet = workbook.addWorksheet('Summary');
    summarySheet.columns = [
      { header: 'Property', key: 'prop', width: 25 },
      { header: 'Value', key: 'val', width: 30 },
    ];

    summarySheet.addRow({ prop: 'Project Name', val: project.name });
    summarySheet.addRow({ prop: 'Crop', val: project.crop || 'N/A' });
    summarySheet.addRow({ prop: 'Status', val: project.status });
    summarySheet.addRow({ prop: 'Land Size', val: `${project.landSize} ${project.landUnit}` });
    summarySheet.addRow({});

    // Financials
    const totalExpenses = project.expenses.reduce((sum, e) => sum + (e.amount || 0), 0);
    const totalLabor = project.workEntries.reduce((sum, w) => sum + (w.totalCost || 0), 0);
    const totalInventory = project.inventoryItems.reduce((sum, i) => sum + (i.totalCost || 0), 0);
    const totalRevenue = project.sales.reduce((sum, s) => sum + (s.totalAmount || 0), 0);
    const totalCost = totalExpenses + totalLabor + totalInventory;

    summarySheet.addRow({ prop: 'Total Revenue', val: totalRevenue });
    summarySheet.addRow({ prop: 'Total Cost', val: totalCost });
    summarySheet.addRow({ prop: 'Net Profit/Loss', val: totalRevenue - totalCost });

    // Expenses Sheet
    const expenseSheet = workbook.addWorksheet('Expenses');
    expenseSheet.columns = [
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Category', key: 'category', width: 20 },
      { header: 'Payee', key: 'payee', width: 25 },
      { header: 'Amount', key: 'amount', width: 15 },
      { header: 'Note', key: 'note', width: 40 },
    ];
    project.expenses.forEach(e => {
      expenseSheet.addRow({
        date: e.date.toLocaleDateString(),
        category: e.category,
        payee: e.payee || e.payeeRecord?.name || 'N/A',
        amount: e.amount,
        note: e.note
      });
    });

    // Labor Sheet
    const laborSheet = workbook.addWorksheet('Labor');
    laborSheet.columns = [
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Worker', key: 'name', width: 25 },
      { header: 'Activity', key: 'activity', width: 25 },
      { header: 'Days', key: 'days', width: 10 },
      { header: 'Cost', key: 'cost', width: 15 },
    ];
    project.workEntries.forEach(w => {
      laborSheet.addRow({
        date: w.date.toLocaleDateString(),
        name: w.employee.name,
        activity: w.activity,
        days: w.daysWorked,
        cost: w.totalCost
      });
    });

    const filename = `Report_${project.name.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.xlsx`;
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    await workbook.xlsx.write(res);
    res.end();

  } catch (error) {
    console.error('Excel Export Error:', error);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate Excel report' });
    }
  }
};

module.exports = {
  generateProjectReport,
  generateProjectExcelReport,
};
