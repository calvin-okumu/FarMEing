const PDFDocument = require('pdfkit');
const ExcelJS = require('exceljs');
const prisma = require('../lib/prisma');
const { verifyProjectAccess } = require('../lib/project-access');

const getProjectData = async (id, userId, res) => {
  const access = await verifyProjectAccess(id, userId, res);
  if (!access) return null;

  return await prisma.farmProject.findUnique({
    where: { id },
    include: {
      budgetItems: { where: { isDeleted: false } },
      expenses: { where: { isDeleted: false }, include: { payeeRecord: true } },
      workEntries: { where: { isDeleted: false }, include: { employee: true } },
      harvests: { where: { isDeleted: false } },
      sales: { where: { isDeleted: false }, include: { salePayments: { where: { isDeleted: false } } } },
      inventoryItems: { where: { isDeleted: false } },
    },
  });
};

const generateProjectReport = async (req, res) => {
  const { id } = req.params;

  try {
    const project = await getProjectData(id, req.user.id, res);
    if (!project) return;

    const doc = new PDFDocument({ margin: 50 });

    // Set filename
    const filename = `Report_${project.name.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`;
    res.setHeader('Content-disposition', `attachment; filename="${filename}"`);
    res.setHeader('Content-type', 'application/pdf');

    doc.pipe(res);

    // ── Header ───────────────────────────────────────────────────────────────
    doc.fontSize(24).text('Farm Project Report', { align: 'center' });
    doc.fontSize(10).text('Generated by Shamba Mkononi', { align: 'center' });
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    doc.moveDown();

    // ── Project Info ─────────────────────────────────────────────────────────
    doc.fontSize(16).text(project.name, { underline: true });
    doc.fontSize(12).text(`Crop: ${project.crop || 'N/A'}`);
    doc.text(`Land Size: ${project.landSize} ${project.landUnit}`);
    doc.text(`Status: ${project.status || 'Active'}`);
    doc.text(`Date: ${project.startDate.toLocaleDateString()} - ${project.endDate ? project.endDate.toLocaleDateString() : 'Present'}`);
    doc.moveDown();

    // ── Financial Summary ────────────────────────────────────────────────────
    const totalBudget = project.budgetItems.reduce((sum, item) => sum + (item.total || 0), 0);
    const totalExpenses = project.expenses.reduce((sum, item) => sum + (item.amount || 0), 0);
    const totalLabor = project.workEntries.reduce((sum, item) => sum + (item.totalCost || 0), 0);
    const totalInventory = project.inventoryItems.reduce((sum, item) => sum + (item.totalCost || 0), 0);
    const totalRevenue = project.sales.reduce((sum, item) => sum + (item.totalAmount || 0), 0);
    const totalCost = totalExpenses + totalLabor + totalInventory;
    const netProfit = totalRevenue - totalCost;
    const collectedRevenue = project.sales.reduce((sum, item) => sum + ((item.totalAmount || 0) - (item.balanceDue || 0)), 0);
    const pendingRevenue = project.sales.reduce((sum, item) => sum + (item.balanceDue || 0), 0);

    doc.fontSize(16).text('Financial Summary', { underline: true });
    doc.fontSize(12);
    doc.text(`Total Revenue: ${totalRevenue.toLocaleString()}`);
    doc.text(`Collected Revenue: ${collectedRevenue.toLocaleString()}${pendingRevenue > 0 ? ` (${pendingRevenue.toLocaleString()} pending)` : ''}`);
    doc.text(`Total Spending: ${totalCost.toLocaleString()}`);
    doc.text(`Net Profit/Loss: ${netProfit.toLocaleString()}`, { 
      color: netProfit >= 0 ? 'green' : 'red' 
    });
    doc.moveDown();

    // ── Breakdown ────────────────────────────────────────────────────────────
    doc.text(`- Operational Expenses: ${totalExpenses.toLocaleString()}`);
    doc.text(`- Labor Costs: ${totalLabor.toLocaleString()}`);
    doc.text(`- Inventory Purchases: ${totalInventory.toLocaleString()}`);
    doc.moveDown();

    // ── Production ───────────────────────────────────────────────────────────
    const totalHarvest = project.harvests.reduce((sum, item) => sum + (item.weight || 0), 0);
    doc.fontSize(16).text('Production', { underline: true });
    doc.fontSize(12).text(`Total Harvest: ${totalHarvest.toLocaleString()} kg`);
    doc.moveDown();

    // ── Budget Breakdown ────────────────────────────────────────────────
    if (project.budgetItems.length > 0) {
      doc.fontSize(16).text('Budget Breakdown', { underline: true });
      doc.fontSize(12);
      project.budgetItems.forEach(item => {
        doc.text(`- ${item.name} (${item.category}): ${item.quantity} ${item.unit} × ${item.unitPrice} = ${item.total}`);
      });
      doc.text(`Total Budget: ${totalBudget.toLocaleString()}`);
      doc.moveDown();
    }

    // ── Harvest Records ──────────────────────────────────────────────────
    if (project.harvests.length > 0) {
      doc.fontSize(16).text('Harvest Records', { underline: true });
      doc.fontSize(12);
      const harvestByCrop = {};
      project.harvests.forEach(h => {
        harvestByCrop[h.crop] = (harvestByCrop[h.crop] || 0) + (h.weight || 0);
      });
      Object.entries(harvestByCrop).forEach(([crop, weight]) => {
        doc.text(`- ${crop}: ${weight.toLocaleString()} kg`);
      });
      doc.text(`Total Harvest: ${totalHarvest.toLocaleString()} kg`);
      doc.text(`Expected Yield: ${project.expectedYield || 'N/A'} kg`);
      doc.moveDown();
    }

    // ── Sales Records ────────────────────────────────────────────────────
    if (project.sales.length > 0) {
      doc.fontSize(16).text('Sales Records', { underline: true });
      doc.fontSize(12);
      project.sales.forEach(sale => {
        doc.text(`- ${sale.customer || 'Cash'}: ${sale.weightSold || 0} kg × ${sale.unitPrice} = ${sale.totalAmount}`);
        doc.text(`  Date: ${sale.date.toLocaleDateString()}`);
        if (sale.paymentStatus && sale.paymentStatus !== 'paid') {
          doc.text(`  Status: ${sale.paymentStatus.charAt(0).toUpperCase() + sale.paymentStatus.slice(1)} — ${sale.balanceDue ? sale.balanceDue.toLocaleString() : 0} due`);
        }
        if (sale.salePayments && sale.salePayments.length > 0) {
          sale.salePayments.forEach(p => {
            doc.text(`    Payment: ${p.amount.toLocaleString()} on ${p.date.toLocaleDateString()}${p.note ? ` — ${p.note}` : ''}`);
          });
        }
      });
      doc.text(`Total Revenue: ${totalRevenue.toLocaleString()}`);
      doc.text(`Collected: ${collectedRevenue.toLocaleString()}${pendingRevenue > 0 ? `, Pending: ${pendingRevenue.toLocaleString()}` : ''}`);
      doc.moveDown();
    }

    // ── Footer ───────────────────────────────────────────────────────────────
    doc.fontSize(10).text('End of Report', doc.page.width - 100, doc.page.height - 50, { align: 'right' });

    doc.end();

  } catch (error) {
    console.error('PDF Export Error:', error);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate PDF report' });
    }
  }
};

const generateProjectExcelReport = async (req, res) => {
  const { id } = req.params;

  try {
    const project = await getProjectData(id, req.user.id, res);
    if (!project) return;

    const workbook = new ExcelJS.Workbook();
    workbook.creator = 'Shamba Mkononi';
    workbook.created = new Date();

    const summarySheet = workbook.addWorksheet('Summary');
    summarySheet.columns = [
      { header: 'Property', key: 'prop', width: 25 },
      { header: 'Value', key: 'val', width: 30 },
    ];

    summarySheet.addRow({ prop: 'Project Name', val: project.name });
    summarySheet.addRow({ prop: 'Crop', val: project.crop || 'N/A' });
    summarySheet.addRow({ prop: 'Status', val: project.status });
    summarySheet.addRow({ prop: 'Land Size', val: `${project.landSize} ${project.landUnit}` });
    summarySheet.addRow({});

    // Financials
    const totalExpenses = project.expenses.reduce((sum, e) => sum + (e.amount || 0), 0);
    const totalLabor = project.workEntries.reduce((sum, w) => sum + (w.totalCost || 0), 0);
    const totalInventory = project.inventoryItems.reduce((sum, i) => sum + (i.totalCost || 0), 0);
    const totalRevenue = project.sales.reduce((sum, s) => sum + (s.totalAmount || 0), 0);
    const totalCost = totalExpenses + totalLabor + totalInventory;
    const collectedRevenue = project.sales.reduce((sum, s) => sum + ((s.totalAmount || 0) - (s.balanceDue || 0)), 0);
    const pendingRevenue = project.sales.reduce((sum, s) => sum + (s.balanceDue || 0), 0);

    summarySheet.addRow({ prop: 'Total Revenue', val: totalRevenue });
    summarySheet.addRow({ prop: 'Collected Revenue', val: collectedRevenue });
    if (pendingRevenue > 0) summarySheet.addRow({ prop: 'Pending Revenue', val: pendingRevenue });
    summarySheet.addRow({ prop: 'Total Cost', val: totalCost });
    summarySheet.addRow({ prop: 'Net Profit/Loss', val: totalRevenue - totalCost });

    // Expenses Sheet
    const expenseSheet = workbook.addWorksheet('Expenses');
    expenseSheet.columns = [
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Category', key: 'category', width: 20 },
      { header: 'Payee', key: 'payee', width: 25 },
      { header: 'Amount', key: 'amount', width: 15 },
      { header: 'Note', key: 'note', width: 40 },
    ];
    project.expenses.forEach(e => {
      expenseSheet.addRow({
        date: e.date.toLocaleDateString(),
        category: e.category,
        payee: e.payee || e.payeeRecord?.name || 'N/A',
        amount: e.amount,
        note: e.note
      });
    });

    // Labor Sheet
    const laborSheet = workbook.addWorksheet('Labor');
    laborSheet.columns = [
      { header: 'Date', key: 'date', width: 15 },
      { header: 'Worker', key: 'name', width: 25 },
      { header: 'Activity', key: 'activity', width: 25 },
      { header: 'Days', key: 'days', width: 10 },
      { header: 'Cost', key: 'cost', width: 15 },
    ];
    project.workEntries.forEach(w => {
      laborSheet.addRow({
        date: w.date.toLocaleDateString(),
        name: w.employee.name,
        activity: w.activity,
        days: w.daysWorked,
        cost: w.totalCost
      });
    });

    // Harvest Sheet
    if (project.harvests.length > 0) {
      const harvestSheet = workbook.addWorksheet('Harvest');
      harvestSheet.columns = [
        { header: 'Date', key: 'date', width: 15 },
        { header: 'Crop', key: 'crop', width: 20 },
        { header: 'Weight (kg)', key: 'weight', width: 15 },
        { header: 'Notes', key: 'notes', width: 40 },
      ];
      project.harvests.forEach(h => {
        harvestSheet.addRow({
          date: h.date.toLocaleDateString(),
          crop: h.crop,
          weight: h.weight,
          notes: h.notes
        });
      });
    }

    // Sales Sheet
    if (project.sales.length > 0) {
      const salesSheet = workbook.addWorksheet('Sales');
      salesSheet.columns = [
        { header: 'Date', key: 'date', width: 15 },
        { header: 'Customer', key: 'customer', width: 25 },
        { header: 'Weight (kg)', key: 'weight', width: 15 },
        { header: 'Unit Price', key: 'price', width: 15 },
        { header: 'Total Amount', key: 'total', width: 15 },
        { header: 'Payment Status', key: 'status', width: 15 },
        { header: 'Balance Due', key: 'balance', width: 15 },
        { header: 'Notes', key: 'notes', width: 40 },
      ];
      project.sales.forEach(s => {
        salesSheet.addRow({
          date: s.date.toLocaleDateString(),
          customer: s.customer || 'Cash',
          weight: s.weightSold,
          price: s.unitPrice,
          total: s.totalAmount,
          status: s.paymentStatus ? s.paymentStatus.charAt(0).toUpperCase() + s.paymentStatus.slice(1) : 'Paid',
          balance: s.balanceDue || 0,
          notes: s.notes
        });
      });
    }

    // Sale Payments Sheet
    const allPayments = project.sales.flatMap(s => (s.salePayments || []).map(p => ({ ...p, customer: s.customer || 'Cash' })));
    if (allPayments.length > 0) {
      const paymentsSheet = workbook.addWorksheet('Sale Payments');
      paymentsSheet.columns = [
        { header: 'Date', key: 'date', width: 15 },
        { header: 'Customer', key: 'customer', width: 25 },
        { header: 'Amount', key: 'amount', width: 15 },
        { header: 'Note', key: 'note', width: 40 },
      ];
      allPayments.forEach(p => {
        paymentsSheet.addRow({
          date: p.date.toLocaleDateString(),
          customer: p.customer,
          amount: p.amount,
          note: p.note || ''
        });
      });
    }

    // Budget Sheet
    if (project.budgetItems.length > 0) {
      const budgetSheet = workbook.addWorksheet('Budget');
      budgetSheet.columns = [
        { header: 'Category', key: 'category', width: 20 },
        { header: 'Item', key: 'item', width: 30 },
        { header: 'Quantity', key: 'qty', width: 12 },
        { header: 'Unit', key: 'unit', width: 10 },
        { header: 'Unit Price', key: 'price', width: 15 },
        { header: 'Total', key: 'total', width: 15 },
      ];
      project.budgetItems.forEach(b => {
        budgetSheet.addRow({
          category: b.category,
          item: b.name,
          qty: b.quantity,
          unit: b.unit,
          price: b.unitPrice,
          total: b.total
        });
      });
    }

    // Inventory Sheet
    if (project.inventoryItems.length > 0) {
      const inventorySheet = workbook.addWorksheet('Inventory');
      inventorySheet.columns = [
        { header: 'Name', key: 'name', width: 25 },
        { header: 'Category', key: 'category', width: 20 },
        { header: 'Quantity', key: 'qty', width: 12 },
        { header: 'Unit', key: 'unit', width: 10 },
        { header: 'Unit Cost', key: 'cost', width: 15 },
        { header: 'Used Qty', key: 'used', width: 12 },
        { header: 'Notes', key: 'notes', width: 40 },
      ];
      project.inventoryItems.forEach(i => {
        inventorySheet.addRow({
          name: i.name,
          category: i.category,
          qty: i.quantity,
          unit: i.unit,
          cost: i.unitCost,
          used: i.usedQty,
          notes: i.notes
        });
      });
    }

    const filename = `Report_${project.name.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.xlsx`;
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    await workbook.xlsx.write(res);
    res.end();

  } catch (error) {
    console.error('Excel Export Error:', error);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate Excel report' });
    }
  }
};

module.exports = {
  generateProjectReport,
  generateProjectExcelReport,
};
